package com.calibratesys.dto;

import org.springframework.data.domain.Page;

import java.util.Collections;
import java.util.List;

/**
 * Standardized pagination response metadata DTO.
 */
public class PageResponseDto<T> {

    private List<T> content;
    private int page;
    private int size;
    private long totalElements;
    private int totalPages;
    private boolean first;
    private boolean last;
    private boolean empty;

    public PageResponseDto() {
        this.content = Collections.emptyList();
    }

    public PageResponseDto(List<T> content, int page, int size, long totalElements, int totalPages,
                           boolean first, boolean last, boolean empty) {
        this.content = content != null ? content : Collections.emptyList();
        this.page = page;
        this.size = size;
        this.totalElements = totalElements;
        this.totalPages = totalPages;
        this.first = first;
        this.last = last;
        this.empty = empty;
    }

    public static <T> PageResponseDto<T> of(List<T> content, int page, int size, long totalElements) {
        int totalPages = size > 0 ? (int) Math.ceil((double) totalElements / size) : 0;
        boolean first = page <= 0;
        boolean last = totalPages == 0 || page >= totalPages - 1;
        boolean empty = content == null || content.isEmpty();
        return new PageResponseDto<>(content, page, size, totalElements, totalPages, first, last, empty);
    }

    public static <T> PageResponseDto<T> from(Page<T> springPage) {
        if (springPage == null) {
            return new PageResponseDto<>(Collections.emptyList(), 0, 0, 0, 0, true, true, true);
        }
        return new PageResponseDto<>(
                springPage.getContent(),
                springPage.getNumber(),
                springPage.getSize(),
                springPage.getTotalElements(),
                springPage.getTotalPages(),
                springPage.isFirst(),
                springPage.isLast(),
                springPage.isEmpty()
        );
    }

    public List<T> getContent() {
        return content;
    }

    public void setContent(List<T> content) {
        this.content = content;
    }

    public int getPage() {
        return page;
    }

    public void setPage(int page) {
        this.page = page;
    }

    public int getSize() {
        return size;
    }

    public void setSize(int size) {
        this.size = size;
    }

    public long getTotalElements() {
        return totalElements;
    }

    public void setTotalElements(long totalElements) {
        this.totalElements = totalElements;
    }

    public int getTotalPages() {
        return totalPages;
    }

    public void setTotalPages(int totalPages) {
        this.totalPages = totalPages;
    }

    public boolean isFirst() {
        return first;
    }

    public void setFirst(boolean first) {
        this.first = first;
    }

    public boolean isLast() {
        return last;
    }

    public void setLast(boolean last) {
        this.last = last;
    }

    public boolean isEmpty() {
        return empty;
    }

    public void setEmpty(boolean empty) {
        this.empty = empty;
    }
}
